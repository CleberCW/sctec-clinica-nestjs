import { HttpException } from '@nestjs/common';

export const ERROR_CODE = {
  DADOS_INVALIDOS: 'DADOS_INVALIDOS',
  NAO_AUTENTICADO: 'NAO_AUTENTICADO',
  CREDENCIAIS_INVALIDAS: 'CREDENCIAIS_INVALIDAS',
  ACESSO_NEGADO: 'ACESSO_NEGADO',
  RECURSO_NAO_ENCONTRADO: 'RECURSO_NAO_ENCONTRADO',
  EMAIL_JA_CADASTRADO: 'EMAIL_JA_CADASTRADO',
  CPF_JA_CADASTRADO: 'CPF_JA_CADASTRADO',
  CRM_JA_CADASTRADO: 'CRM_JA_CADASTRADO',
  HORARIO_INDISPONIVEL: 'HORARIO_INDISPONIVEL',
  PACIENTE_INDISPONIVEL: 'PACIENTE_INDISPONIVEL',
  HORARIO_FORA_DA_ESCALA: 'HORARIO_FORA_DA_ESCALA',
  TRANSICAO_INVALIDA: 'TRANSICAO_INVALIDA',
} as const;

export type ERROR_CODE = (typeof ERROR_CODE)[keyof typeof ERROR_CODE];

export const HTTP_STATUS_BY_CODE = {
  DADOS_INVALIDOS: 400,
  NAO_AUTENTICADO: 401,
  CREDENCIAIS_INVALIDAS: 401,
  ACESSO_NEGADO: 403,
  RECURSO_NAO_ENCONTRADO: 404,
  EMAIL_JA_CADASTRADO: 409,
  CPF_JA_CADASTRADO: 409,
  CRM_JA_CADASTRADO: 409,
  HORARIO_INDISPONIVEL: 409,
  PACIENTE_INDISPONIVEL: 409,
  HORARIO_FORA_DA_ESCALA: 422,
  TRANSICAO_INVALIDA: 422,
} as const satisfies Record<ERROR_CODE, number>;

export type HTTP_STATUS_BY_CODE =
  (typeof HTTP_STATUS_BY_CODE)[keyof typeof HTTP_STATUS_BY_CODE];

export class DomainError extends HttpException {
  constructor(message: string | string[], code: ERROR_CODE) {
    const statusCode = HTTP_STATUS_BY_CODE[code];

    super(
      {
        statusCode,
        code,
        message,
      },
      statusCode,
    );
  }
}
